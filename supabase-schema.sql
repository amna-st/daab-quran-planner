-- بيانات كل مستخدمة خاصة بها
create table if not exists public.daab_data (
  user_id uuid primary key references auth.users(id) on delete cascade,
  data jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);
alter table public.daab_data enable row level security;
drop policy if exists "Read own Daab data" on public.daab_data;
drop policy if exists "Insert own Daab data" on public.daab_data;
drop policy if exists "Update own Daab data" on public.daab_data;
create policy "Read own Daab data" on public.daab_data for select using (auth.uid() = user_id);
create policy "Insert own Daab data" on public.daab_data for insert with check (auth.uid() = user_id);
create policy "Update own Daab data" on public.daab_data for update using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- تحديات الحفظ المشتركة
create table if not exists public.daab_challenges (
  id bigint generated by default as identity primary key,
  creator_id uuid not null references auth.users(id) on delete cascade,
  title text not null check (char_length(title) between 3 and 100),
  days integer not null check (days between 1 and 100),
  target_pages integer not null check (target_pages between 1 and 20),
  created_at timestamptz not null default now()
);
create table if not exists public.daab_challenge_members (
  challenge_id bigint not null references public.daab_challenges(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  joined_at timestamptz not null default now(),
  primary key (challenge_id,user_id)
);
alter table public.daab_challenges enable row level security;
alter table public.daab_challenge_members enable row level security;
drop policy if exists "Authenticated can view challenges" on public.daab_challenges;
drop policy if exists "Users create own challenges" on public.daab_challenges;
drop policy if exists "Authenticated can view challenge members" on public.daab_challenge_members;
drop policy if exists "Users join as themselves" on public.daab_challenge_members;
create policy "Authenticated can view challenges" on public.daab_challenges for select to authenticated using (true);
create policy "Users create own challenges" on public.daab_challenges for insert to authenticated with check (auth.uid() = creator_id);
create policy "Authenticated can view challenge members" on public.daab_challenge_members for select to authenticated using (true);
create policy "Users join as themselves" on public.daab_challenge_members for insert to authenticated with check (auth.uid() = user_id);

-- مجتمع المشاركات التشجيعية: منشورات نصية قصيرة فقط
create table if not exists public.daab_posts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  display_name text not null default 'رفيقة دَأْب' check (char_length(display_name) <= 40),
  body text not null check (char_length(body) between 1 and 500),
  created_at timestamptz not null default now()
);
alter table public.daab_posts enable row level security;
drop policy if exists "Authenticated can read community posts" on public.daab_posts;
drop policy if exists "Users publish as themselves" on public.daab_posts;
create policy "Authenticated can read community posts" on public.daab_posts for select to authenticated using (true);
create policy "Users publish as themselves" on public.daab_posts for insert to authenticated with check (auth.uid() = user_id);

-- تسجيل تقدم كل عضوة داخل التحديات
create table if not exists public.daab_challenge_progress (
  id bigint generated by default as identity primary key,
  challenge_id bigint not null references public.daab_challenges(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  pages_done integer not null check (pages_done between 1 and 100),
  created_at timestamptz not null default now()
);
alter table public.daab_challenge_progress enable row level security;
drop policy if exists "Authenticated can read challenge progress" on public.daab_challenge_progress;
drop policy if exists "Users record own challenge progress" on public.daab_challenge_progress;
create policy "Authenticated can read challenge progress" on public.daab_challenge_progress for select to authenticated using (true);
create policy "Users record own challenge progress" on public.daab_challenge_progress for insert to authenticated with check (auth.uid() = user_id);
